import { createRequire } from "node:module";
import assert from "node:assert/strict";
import { fileURLToPath } from "node:url";
import { mkdir } from "node:fs/promises";
import { selectPreference } from "./preferences.mjs";
const require = createRequire(import.meta.url);
await mkdir(new URL("../qa/", import.meta.url), { recursive: true });
const { chromium } = require(process.env.PLAYWRIGHT_MODULE_PATH || "playwright");
const browser = await chromium.launch({ channel: process.env.PLAYWRIGHT_CHANNEL || "msedge" });
try {
    const context = await browser.newContext({ locale: "en-US", reducedMotion: "reduce" });
    await context.addInitScript(() => {
        window.writes = [];
        Object.defineProperty(navigator, "clipboard", { value: { writeText: async (text) => {
                    if (window.denyCopy) throw new Error("Denied");
                    window.writes.push(text);
                } } });
    });
    const page = await context.newPage();
    const errors = [];
    page.on("pageerror", (error) => errors.push(error.message));
    await page.route("https://api.github.com/**", (route) => route.fulfill({ json: { tag_name: "test", assets: [] } }));
    await page.goto(process.env.WEBSITE_URL || "http://127.0.0.1:5173/");
    const demo = page.frameLocator("iframe.product-demo");
    const cards = demo.locator("[data-clip-card]");
    await cards.first().waitFor();
    await demo.locator("html[lang=en]").waitFor();
    await page.locator("iframe.product-demo").evaluate((element) => element.scrollIntoView({ block: "center" }));
    assert.equal(await cards.count(), 6);
    await demo.getByRole("button", { name: "Filter by type", exact: true }).click();
    await demo.getByRole("menuitemradio", { name: "Files", exact: true }).click();
    assert.equal(await cards.count(), 1);
    assert.ok((await cards.first().textContent()).includes("Project-notes.pdf"));
    await demo.getByRole("searchbox").fill("Chrome");
    assert.equal(await cards.count(), 0, "Type and search filters combine");
    await demo.getByRole("searchbox").fill("");
    await demo.getByRole("button", { name: "Clear type filter", exact: true }).click();
    assert.equal(await cards.count(), 6);
    await demo.getByRole("button", { name: "Filter by type", exact: true }).click();
    await demo.getByRole("menuitemradio", { name: "Text", exact: true }).click();
    assert.equal(await cards.count(), 5, "Text includes plain and rich text");
    await demo.getByRole("button", { name: "Filter by type", exact: true }).click();
    await demo.getByRole("menuitemradio", { name: "Image", exact: true }).click();
    assert.equal(await cards.count(), 0, "No image samples should show the real empty state");
    await page.getByRole("button", { name: "Reset demo", exact: true }).click();
    await demo.getByText("6 records", { exact: true }).waitFor();
    await demo.getByRole("searchbox").fill("Chrome");
    assert.equal(await cards.count(), 1);
    await demo.getByRole("searchbox").fill("");
    await cards.first().click();
    assert.equal(await demo.locator("body").evaluate(() => window.writes.length), 0, "Single click does not copy");
    await cards.first().dblclick();
    await page.getByText("Sample text copied", { exact: true }).waitFor();
    const linkCard = cards.filter({ hasText: "https://github.com/Heyiki/TrayClip" });
    await linkCard.hover();
    const copy = linkCard.getByRole("button", { name: "Copy", exact: true });
    await page.waitForTimeout(180);
    assert.equal(await copy.evaluate((element) => getComputedStyle(element.closest(".clip-actions")).opacity), "1");
    await copy.click();
    assert.equal(await demo.locator("body").evaluate(() => window.writes.at(-1)), "https://github.com/Heyiki/TrayClip");
    await linkCard.hover();
    await linkCard.getByRole("button", { name: "Pin", exact: true }).click();
    await linkCard.hover();
    await linkCard.getByRole("button", { name: "Unpin", exact: true }).waitFor();
    await demo.locator("body").evaluate(() => { window.denyCopy = true; });
    await cards.first().dblclick();
    await page.getByText("Your browser blocked copying.", { exact: false }).waitFor();
    await cards.first().click({ button: "right" });
    await demo.getByRole("menuitem", { name: "Copy", exact: true }).waitFor();
    await demo.locator("body").press("Escape");
    await linkCard.hover();
    await linkCard.getByRole("button", { name: "Delete", exact: true }).click();
    assert.equal(await cards.count(), 5);
    await page.getByRole("button", { name: "Reset demo", exact: true }).click();
    await demo.getByText("6 records", { exact: true }).waitFor();
    assert.equal(await cards.count(), 6);
    await demo.getByRole("button", { name: "Ideas", exact: true }).click();
    assert.equal(await cards.count(), 1);
    await demo.getByRole("button", { name: "All", exact: true }).click();
    await demo.getByRole("button", { name: "New group", exact: true }).click();
    const groupInput = demo.locator("[data-slot='group-bar'] input");
    await groupInput.fill("Demo");
    await groupInput.press("Enter");
    await demo.getByRole("button", { name: "Demo", exact: true }).waitFor();
    await demo.getByRole("button", { name: "Demo", exact: true }).click({ button: "right" });
    await demo.getByRole("menuitem", { name: "Rename", exact: true }).click();
    await groupInput.fill("Renamed");
    await groupInput.press("Enter");
    await demo.getByRole("button", { name: "Renamed", exact: true }).waitFor();
    await demo.getByRole("button", { name: "All", exact: true }).click();
    await page.locator("iframe.product-demo").evaluate((element) => element.scrollIntoView({ block: "center" }));
    await cards.first().hover();
    await cards.first().getByRole("button", { name: "Search group", exact: false }).click();
    await demo.getByRole("dialog").getByRole("button", { name: "Renamed", exact: true }).click();
    await demo.getByRole("button", { name: "Renamed", exact: true }).click();
    assert.equal(await cards.count(), 1);
    await demo.getByRole("button", { name: "Renamed", exact: true }).click({ button: "right" });
    await demo.getByRole("menuitem", { name: "Delete group", exact: true }).click();
    await demo.getByRole("button", { name: "Renamed", exact: true }).waitFor({ state: "detached" });
    await demo.getByText("6 records", { exact: true }).waitFor();
    await demo.getByRole("button", { name: "Close window", exact: true }).click();
    await page.getByText("This action requires the desktop app.", { exact: false }).waitFor();
    await selectPreference(page, "Language", "zh-CN");
    await demo.locator("html[lang='zh-CN']").waitFor();
    for (const width of [320, 390, 768, 1440]) {
        await page.setViewportSize({ width, height: 1000 });
        for (const theme of ["light", "dark"]) {
            await selectPreference(page, "外观", theme);
            await demo.locator(`html[data-theme=${theme}]`).waitFor();
            await page.waitForTimeout(200);
            assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
            assert.equal(await demo.locator("html").evaluate((element) => element.scrollWidth > innerWidth), false);
            await page.locator("iframe").scrollIntoViewIfNeeded();
            await page.screenshot({ path: fileURLToPath(new URL(`../qa/real-demo-${theme}-${width}.png`, import.meta.url)) });
        }
    }
    assert.deepEqual(errors, []);
    console.log("PASS: real components, search, group CRUD/move, single/double click, hover actions, pin/delete/reset, context menu, copy success/denial, unavailable desktop actions, bilingual sync and 8 responsive themes");
    await context.close();
} finally { await browser.close(); }
